import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { resolveRuntimeContract } from '../materialize/server-runner.mjs';

/**
 * Turns a generated full-app workspace into something anyone can run and test from outside the benchmark:
 * a Dockerfile built from the same start contract the audit used, plus a source archive. Nothing is deployed
 * and nothing costs money; the report links both so a reader can build the exact site that was scored.
 */

export const CONTAINER_PORT = 8080;
const INNER_PORT = 8081;
const NESTED_PACKAGE_DIRS = ['client', 'frontend', 'web', 'server', 'backend', 'api'];
export const SOURCE_EXCLUDES = ['node_modules', '.git', '.next/cache', '.venv', 'venv', '__pycache__', '.cache', '*.heapsnapshot', '*.log'];
const MAX_SOURCE_BYTES = 25 * 1024 * 1024;

export function detectRuntimeKind(workspaceDir, contract) {
  const has = (f) => existsSync(join(workspaceDir, f));
  const start = `${contract?.startCommand || ''} ${contract?.buildCommand || ''}`;
  const node = has('package.json') || /\b(?:node|npm|npx|pnpm|yarn|bun)\b/.test(start);
  const python = has('requirements.txt') || has('pyproject.toml') || /\bpython3?\b|\buvicorn\b|\bgunicorn\b|\bflask\b/.test(start);
  const go = has('go.mod') || /\bgo (?:run|build)\b|bench-app/.test(start);
  if (go && !node && !python) return 'go';
  if (python && node) return 'node+python';
  if (python) return 'python';
  return 'node';
}

const sh = (cmd) => JSON.stringify(['sh', '-c', cmd]);

/** The Dockerfile text for a workspace, or null when there is no start command to build it from. */
export function buildDockerfile({ workspaceDir, contract = resolveRuntimeContract(workspaceDir) } = {}) {
  if (!contract?.startCommand) return null;
  const kind = detectRuntimeKind(workspaceDir, contract);
  const has = (f) => existsSync(join(workspaceDir, f));
  const L = [
    '# Generated by the Web Outcomes Benchmark from the start contract used to score this site.',
    '# Build:  docker build -t generated-site .',
    `# Run:    docker run --rm -p ${CONTAINER_PORT}:${CONTAINER_PORT} generated-site   then open http://localhost:${CONTAINER_PORT}`,
  ];
  const apt = ['socat', 'ca-certificates'];
  if (kind === 'go') {
    L.push('FROM golang:1.23-bookworm');
  } else if (kind === 'python') {
    L.push('FROM python:3.12-slim-bookworm');
  } else {
    L.push('FROM node:22-bookworm-slim');
    apt.push('python3', 'make', 'g++'); // native modules such as better-sqlite3
    if (kind === 'node+python') apt.push('python3-pip', 'python3-venv');
  }
  L.push(`RUN apt-get update && apt-get install -y --no-install-recommends ${apt.join(' ')} && rm -rf /var/lib/apt/lists/*`);
  L.push('WORKDIR /app', 'COPY . .');
  if (kind === 'node' || kind === 'node+python') {
    const install = 'npm install --include=dev --no-audit --no-fund --legacy-peer-deps';
    if (has('package.json')) L.push(`RUN ${install}`);
    for (const sub of NESTED_PACKAGE_DIRS) if (has(join(sub, 'package.json'))) L.push(`RUN cd ${sub} && ${install}`);
  }
  if (kind === 'python' || kind === 'node+python') {
    const pip = kind === 'python' ? 'pip install --no-cache-dir' : 'pip3 install --no-cache-dir --break-system-packages';
    if (has('requirements.txt')) L.push(`RUN ${pip} -r requirements.txt`);
    else if (has('pyproject.toml')) L.push(`RUN ${pip} .`);
  }
  if (has('start.sh')) L.push('RUN chmod +x start.sh');
  L.push(`ENV NODE_ENV=production PORT=${INNER_PORT} CI=true`);
  if (contract.buildCommand) L.push(`RUN ${contract.buildCommand}`);
  L.push(`EXPOSE ${CONTAINER_PORT}`);
  if (contract.healthPath) {
    L.push(`HEALTHCHECK --interval=10s --timeout=3s --start-period=20s CMD ${sh(`exec 3<>/dev/tcp/127.0.0.1/${INNER_PORT}`).replace('"sh"', '"bash"')}`);
  }
  // The app listens on an inner port, which may be bound to localhost only; socat publishes it on every
  // interface so `-p` works however the generated server chose to bind.
  L.push(`CMD ${sh(`socat TCP-LISTEN:${CONTAINER_PORT},fork,reuseaddr TCP:127.0.0.1:${INNER_PORT} & exec ${contract.startCommand}`)}`);
  return `${L.join('\n')}\n`;
}

export const DOCKERIGNORE = `${['node_modules', '**/node_modules', '.git', '.venv', 'venv', '__pycache__', '*.log', 'Dockerfile'].join('\n')}\n`;

/** Values of credential-like environment variables on this machine: none of them may leave in an archive. */
export function liveSecretValues(env = process.env) {
  return Object.entries(env)
    .filter(([k, v]) => /KEY|TOKEN|SECRET|PASSWORD|AUTH/i.test(k) && typeof v === 'string' && v.length >= 12)
    .map(([, v]) => v);
}

function workspaceContainsAny(dir, needles, depth = 0) {
  if (needles.length === 0 || depth > 6) return null;
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name === '.git') continue;
    const full = join(dir, name);
    let st;
    try {
      st = statSync(full);
    } catch {
      continue;
    }
    if (st.isDirectory()) {
      const hit = workspaceContainsAny(full, needles, depth + 1);
      if (hit) return hit;
    } else if (st.size <= 2 * 1024 * 1024) {
      const text = readFileSync(full, 'latin1');
      if (needles.some((n) => text.includes(n))) return full;
    }
  }
  return null;
}

/**
 * Writes `Dockerfile`, `.dockerignore`, `source.tar.gz` and `README.md` for one cell into `outDir`.
 * Returns what was written, or `{ ok: false, reason }` when the cell is not a runnable server.
 */
export function writeCellContainerKit({ cellDir, outDir, materialization, publicBaseUrl = '', env = process.env }) {
  const workspaceDir = join(cellDir, materialization?.runtimeDirRel || 'agent-workspace');
  if (materialization?.serverArchitecture !== 'production-server' || !existsSync(workspaceDir)) {
    return { ok: false, reason: 'not a server build' };
  }
  const contract = resolveRuntimeContract(workspaceDir);
  const dockerfile = buildDockerfile({ workspaceDir, contract });
  if (!dockerfile) return { ok: false, reason: 'no start command found' };

  mkdirSync(outDir, { recursive: true });
  writeFileSync(join(outDir, 'Dockerfile'), dockerfile, 'utf8');
  writeFileSync(join(outDir, 'dockerignore.txt'), DOCKERIGNORE, 'utf8');

  let source = { included: false, reason: null, bytes: 0 };
  const leaked = workspaceContainsAny(workspaceDir, liveSecretValues(env));
  if (leaked) {
    source.reason = 'the workspace contains a credential from the build machine, so its source is not published';
  } else {
    const tarPath = join(outDir, 'source.tar.gz');
    const res = spawnSync('tar', ['-czf', tarPath, ...SOURCE_EXCLUDES.map((e) => `--exclude=${e}`), '-C', workspaceDir, '.'], { encoding: 'utf8', timeout: 60000 });
    const bytes = res.status === 0 && existsSync(tarPath) ? statSync(tarPath).size : 0;
    if (res.status !== 0 || bytes === 0) source.reason = `could not archive the workspace (${(res.stderr || 'tar failed').trim().slice(0, 120)})`;
    else if (bytes > MAX_SOURCE_BYTES) {
      writeFileSync(tarPath, '');
      source.reason = `the source archive is ${(bytes / 1048576).toFixed(0)} MB, over the ${MAX_SOURCE_BYTES / 1048576} MB publishing limit`;
    } else source = { included: true, reason: null, bytes };
  }

  // `{base}` stands for the public address of this folder; the report fills it in with its own URL.
  const commands = source.included
    ? ['mkdir generated-site && cd generated-site', 'curl -L {base}source.tar.gz | tar xz', 'curl -L -o Dockerfile {base}Dockerfile', 'curl -L -o .dockerignore {base}dockerignore.txt', 'docker build -t generated-site .', `docker run --rm -p ${CONTAINER_PORT}:${CONTAINER_PORT} generated-site`]
    : ['docker build -t generated-site .', `docker run --rm -p ${CONTAINER_PORT}:${CONTAINER_PORT} generated-site`];
  const base = publicBaseUrl ? `${publicBaseUrl.replace(/\/+$/, '')}/` : '<address of this folder>/';
  writeFileSync(
    join(outDir, 'README.md'),
    `# Run this generated site yourself\n\nThis is the site exactly as the model wrote it, with a Dockerfile made from the start command the benchmark used.\nIt is unreviewed, machine-written code: run it in a container, not directly on your machine, and do not put it on the public internet.\n\n\`\`\`sh\n${commands.join('\n').replaceAll('{base}', base)}\n\`\`\`\n\nThen open http://localhost:${CONTAINER_PORT}.\n\n- Start command: \`${contract.startCommand}\`\n${contract.buildCommand ? `- Build command: \`${contract.buildCommand}\`\n` : ''}${source.included ? '' : `- Source archive not included: ${source.reason}.\n`}`,
    'utf8'
  );
  return {
    ok: true,
    runtime: detectRuntimeKind(workspaceDir, contract),
    startCommand: contract.startCommand,
    buildCommand: contract.buildCommand || null,
    port: CONTAINER_PORT,
    sourceIncluded: source.included,
    sourceBytes: source.bytes,
    sourceOmittedReason: source.reason,
    commands,
  };
}
